"""Writes LICENSES.md: the license and credit of every media of the demo library."""

from collections.abc import Sequence
from pathlib import Path

from .install import relative_path
from .manifest import MediaEntry

LICENSES_FILE = "LICENSES.md"

HEADER = """# Demo library licenses

Every media of this library is released under a Creative Commons license that allows
sharing it, provided it is credited. Generated by `scripts/fetch-demo-library.py`: do not
edit by hand.
"""


def render(entries: Sequence[MediaEntry]) -> str:
    """Returns the content of LICENSES.md for the given entries."""
    sections = [_render_entry(entry) for entry in entries]
    return HEADER + "\n" + "\n".join(sections)


def write(library_root: Path, entries: Sequence[MediaEntry]) -> Path:
    path = library_root / LICENSES_FILE
    library_root.mkdir(parents=True, exist_ok=True)
    path.write_text(render(entries), encoding="utf-8", newline="\n")
    return path


def _render_entry(entry: MediaEntry) -> str:
    return (
        f"## {entry.title} ({entry.year})\n"
        f"\n"
        f"- File: `{relative_path(entry)}`\n"
        f"- License: [{entry.license}]({entry.license_url})\n"
        f"- Credit: {entry.attribution}\n"
        f"- Source: <{entry.source_page}>\n"
    )
